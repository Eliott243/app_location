/** Helper: get featured listings */
export const featuredListings = mockListings.filter((l) => l.featured);

/** Helper: get by slug */
export function getListingBySlug(slug: string): Listing | undefined {
  return mockListings.find((l) => l.slug === slug);
}

/** Helper: get similar listings (same type, exclude self) */
export function getSimilarListings(listing: Listing, limit = 3): Listing[] {
  return mockListings
    .filter((l) => l.id !== listing.id && l.type === listing.type)
    .slice(0, limit);
}
